using System.Security.Cryptography.X509Certificates;

namespace Air.Cloud.Modules.ReverseTunnel.Server;

/// <summary>
/// <para>zh-cn:Agent 证书续签服务，用于已通过 mTLS 认证的 Agent 在续签窗口内换取下一张客户端证书。</para>
/// <para>en-us:Agent certificate-renewal service used by an mTLS-authenticated Agent to obtain the next client certificate inside the renewal window.</para>
/// </summary>
public interface IReverseTunnelAgentCertificateRenewalService
{
    /// <summary>
    /// <para>zh-cn:使用当前 mTLS 客户端证书认证 Agent，并为新的 CSR 签发下一张证书。该方法不使用 Enrollment token。</para>
    /// <para>en-us:Authenticates the Agent with the current mTLS client certificate and issues the next certificate for a new CSR. The method does not use an enrollment token.</para>
    /// </summary>
    /// <param name="currentCertificate">
    /// <para>zh-cn:当前 gRPC 连接上的 Agent 客户端证书。</para>
    /// <para>en-us:Agent client certificate on the current gRPC connection.</para>
    /// </param>
    /// <param name="declaredAgentId">
    /// <para>zh-cn:续签请求中可选声明的 AgentId。该值只用于与证书身份做一致性校验。</para>
    /// <para>en-us:Optional AgentId declared by the renewal request. It is used only for consistency checks against certificate identity.</para>
    /// </param>
    /// <param name="certificateSigningRequest">
    /// <para>zh-cn:Agent 使用本地新私钥生成的 DER 编码 PKCS#10 CSR。</para>
    /// <para>en-us:DER-encoded PKCS#10 CSR generated by the Agent with a new local private key.</para>
    /// </param>
    /// <param name="utcNow">
    /// <para>zh-cn:用于校验当前证书有效期和续签窗口的 UTC 当前时间。</para>
    /// <para>en-us:Current UTC time used to validate the current certificate and renewal window.</para>
    /// </param>
    /// <returns>
    /// <para>zh-cn:包含新证书或失败原因的续签结果。</para>
    /// <para>en-us:Renewal result containing the new certificate or a failure reason.</para>
    /// </returns>
    ReverseTunnelAgentCertificateRenewalResult Renew(X509Certificate2? currentCertificate, string? declaredAgentId, byte[] certificateSigningRequest, DateTimeOffset utcNow);
}
