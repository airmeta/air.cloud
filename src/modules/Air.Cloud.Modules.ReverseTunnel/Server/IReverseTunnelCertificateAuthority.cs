using System.Security.Cryptography.X509Certificates;

namespace Air.Cloud.Modules.ReverseTunnel.Server;

/// <summary>
/// <para>zh-cn:反向隧道 Server 侧证书颁发机构。实现必须从挂载磁盘或 Secret 加载 CA 私钥，不能从数据库或普通配置读取私钥材料。</para>
/// <para>en-us:Certificate authority used by the reverse tunnel Server. Implementations must load the CA private key from mounted disk or Secret material, never from a database or ordinary configuration.</para>
/// </summary>
public interface IReverseTunnelCertificateAuthority
{
    /// <summary>
    /// <para>zh-cn:加载当前 Server 用于签发 Agent 证书的 CA 证书。调用方应把返回对象视为包含私钥的敏感对象并及时释放。</para>
    /// <para>en-us:Loads the CA certificate currently used by the Server to issue Agent certificates. Callers should treat the returned object as sensitive because it contains the private key, and dispose it promptly.</para>
    /// </summary>
    /// <returns>
    /// <para>zh-cn:包含私钥的 CA 证书实例。</para>
    /// <para>en-us:A CA certificate instance containing the private key.</para>
    /// </returns>
    X509Certificate2 LoadIssuerCertificate();

    /// <summary>
    /// <para>zh-cn:使用当前 CA 为 Agent 的 PKCS#10 CSR 签发客户端证书。该方法只使用 CSR 中的公钥，Subject、SAN、用途和有效期由 Server 策略决定。</para>
    /// <para>en-us:Issues a client certificate for an Agent PKCS#10 CSR by using the current CA. The method uses only the public key from the CSR; subject, SAN, key usage, and validity are decided by Server policy.</para>
    /// </summary>
    /// <param name="agentId">
    /// <para>zh-cn:Server 已确认的 Agent 稳定身份，写入证书 Subject 和 DNS SAN。</para>
    /// <para>en-us:Stable Agent identity confirmed by the Server and written to the certificate subject and DNS SAN.</para>
    /// </param>
    /// <param name="certificateSigningRequest">
    /// <para>zh-cn:Agent 生成的 DER 编码 PKCS#10 CSR。CSR 不得包含 Agent 私钥。</para>
    /// <para>en-us:DER-encoded PKCS#10 CSR generated by the Agent. The CSR must not contain the Agent private key.</para>
    /// </param>
    /// <param name="notBeforeUtc">
    /// <para>zh-cn:签发证书的 UTC 生效时间。</para>
    /// <para>en-us:UTC activation time for the issued certificate.</para>
    /// </param>
    /// <returns>
    /// <para>zh-cn:不包含私钥的 Agent 客户端证书。</para>
    /// <para>en-us:Agent client certificate without a private key.</para>
    /// </returns>
    X509Certificate2 SignAgentCertificate(string agentId, byte[] certificateSigningRequest, DateTimeOffset notBeforeUtc);
}
